import { type Project, type EvidenceRecord, type SavedCreative } from "./project-store.ts";
import { formatIndianCurrency } from "./outreach-engine.ts";

export type ExportFormat = "markdown" | "json";

export type ProjectExportPackage = {
  version: string;
  exportedAt: string;
  project: Project;
  stats: {
    totalTasks: number;
    completedTasks: number;
    evidenceRecordsCount: number;
    savedCreativesCount: number;
    budgetStatus: string;
  };
};

/**
 * Builds a complete machine-readable JSON export bundle for the given project.
 */
export function generateProjectJsonPackage(project: Project): ProjectExportPackage {
  const completedTasks = project.tasks.filter((t) => t.state === "success").length;
  const budgetStatus = project.budgetValidation?.status || "unvalidated";

  return {
    version: "1.0.0",
    exportedAt: new Date().toISOString(),
    project,
    stats: {
      totalTasks: project.tasks.length,
      completedTasks,
      evidenceRecordsCount: project.evidence.length,
      savedCreativesCount: (project.creatives || []).length,
      budgetStatus,
    },
  };
}

/**
 * Formats a clean, executive-level Markdown report suitable for judges, mentors, and sponsors.
 */
export function generateProjectMarkdownReport(project: Project): string {
  const completed = project.tasks.filter((t) => t.state === "success").length;
  const approved = project.tasks.filter((t) => t.state === "approved").length;
  const pending = project.tasks.filter((t) => t.state === "pending").length;

  const targetBudgetStr = project.targetBudget > 0
    ? `₹${formatIndianCurrency(project.targetBudget)}`
    : "Not specified";

  const lines: string[] = [];

  // Header & Metadata
  lines.push(`# OpsPilot Project Operations Report: ${project.name}`);
  lines.push(`> Generated by OpsPilot AI Operations Agent · Workspace: \`${project.id}\``);
  lines.push("");
  lines.push(`- **Target Budget:** ${targetBudgetStr}`);
  lines.push(`- **Task Completion:** ${completed}/${project.tasks.length} tasks completed (${approved} approved, ${pending} pending)`);
  lines.push(`- **Created At:** ${project.createdAt}`);
  lines.push(`- **Last Updated:** ${project.updatedAt}`);
  lines.push("");

  // Executive Summary & Brief
  lines.push("## 1. Executive Summary & Event Brief");
  lines.push("");
  lines.push(`**Description:** ${project.description || "N/A"}`);
  lines.push("");
  lines.push(`**Operational Brief:**`);
  lines.push(`> ${project.brief.replace(/\n/g, "\n> ")}`);
  lines.push("");

  // Structured Event Plan
  lines.push("## 2. Structured Operational Plan");
  lines.push("");
  if (project.structuredPlan) {
    const sp = project.structuredPlan;
    lines.push(`- **Official Event Name:** ${sp.eventName}`);
    lines.push(`- **Expected Participants:** ${sp.participants}`);
    lines.push(`- **Total Planned Budget:** ₹${formatIndianCurrency(sp.totalBudget)}`);
    lines.push("");
    lines.push(`### Summary`);
    lines.push(sp.summary);
    lines.push("");

    if (sp.budget && sp.budget.length > 0) {
      lines.push("### Budget Allocation Breakdown");
      lines.push("");
      lines.push("| Category | Allocated Amount | Operational Details |");
      lines.push("| :--- | :--- | :--- |");
      for (const b of sp.budget) {
        lines.push(`| **${b.category}** | ₹${formatIndianCurrency(b.amount)} | ${b.details} |`);
      }
      lines.push("");
    }

    if (sp.schedule && sp.schedule.length > 0) {
      lines.push("### Operational Schedule");
      lines.push("");
      lines.push("| Time | Activity | Notes |");
      lines.push("| :--- | :--- | :--- |");
      for (const s of sp.schedule) {
        lines.push(`| \`${s.time}\` | **${s.activity}** | ${s.details || "—"} |`);
      }
      lines.push("");
    }

    if (sp.risks && sp.risks.length > 0) {
      lines.push("### Risk Assessment & Mitigations");
      lines.push("");
      for (const r of sp.risks) {
        lines.push(`- ⚠️ **Risk:** ${r.risk}`);
        lines.push(`  - *Mitigation:* ${r.mitigation}`);
      }
      lines.push("");
    }
  } else {
    lines.push(`- **Operational Plan Status:** Workspace plan initialized. AI plan generation available via \`/api/plan\`.`);
    lines.push(`- **Target Event Scope:** ${project.name}`);
    lines.push("");
  }

  // Budget Validation
  lines.push("## 3. Mathematical Budget Verification");
  lines.push("");
  if (project.budgetValidation) {
    const bv = project.budgetValidation;
    lines.push(`- **Validation Status:** \`${bv.status.toUpperCase()}\``);
    lines.push(`- **Requested Limit:** ₹${formatIndianCurrency(bv.requested)}`);
    lines.push(`- **Allocated Total:** ₹${formatIndianCurrency(bv.allocated)}`);
    lines.push(`- **Difference:** ${bv.difference > 0 ? "+" : ""}₹${formatIndianCurrency(bv.difference)}`);
    lines.push("");
    if (bv.warnings.length > 0) {
      lines.push(`**Warnings:**`);
      for (const w of bv.warnings) {
        lines.push(`- ⚠️ ${w}`);
      }
      lines.push("");
    }
  } else {
    lines.push(`- **Status:** Target budget set to ${targetBudgetStr}. Detailed line-item breakdown awaiting AI plan or manual assignment.`);
    lines.push("");
  }

  // Task Execution Checklist
  lines.push("## 4. Operational Tasks & Execution Status");
  lines.push("");
  lines.push("| Priority | State | Task Title | Category | Tool |");
  lines.push("| :--- | :--- | :--- | :--- | :--- |");
  for (const t of project.tasks) {
    const stateBadge = t.state === "success" ? "✅ Success" : t.state === "approved" ? "🟢 Approved" : t.state === "running" ? "⏳ Running" : "⚪ Pending";
    lines.push(`| \`${t.priority.toUpperCase()}\` | ${stateBadge} | **${t.title}** | ${t.category} | \`${t.toolName || "manual"}\` |`);
  }
  lines.push("");

  // Evidence Ledger (Audit Trail)
  lines.push("## 5. Operations Audit Ledger");
  lines.push("");
  lines.push(`Total recorded audit entries: ${project.evidence.length}`);
  lines.push("");
  if (project.evidence.length === 0) {
    lines.push("*No evidence records recorded yet.*");
  } else {
    lines.push("| Timestamp | Event Type | Action / Tool | Verification Level | Status | Details |");
    lines.push("| :--- | :--- | :--- | :--- | :--- | :--- |");
    for (const ev of project.evidence) {
      const toolStr = ev.toolName ? `\`[${ev.toolName}]\`` : "";
      const eventLabel = ev.eventType ? ev.eventType.replace(/_/g, " ") : "event";
      const statusIcon = ev.status === "success" ? "✔ Success" : ev.status === "failed" ? "❌ Failed" : "📝 Recorded";
      const vLevel = ev.verificationLevel === "external_response"
        ? "External Response"
        : ev.verificationLevel === "independently_verified"
        ? "Independently Verified"
        : "Local Execution";
      const cleanDetails = ev.details.replace(/\|/g, "\\|").replace(/\n/g, " ");
      lines.push(`| \`${ev.timestamp.slice(0, 19).replace("T", " ")}\` | ${eventLabel} | **${ev.action}** ${toolStr} | \`${vLevel}\` | ${statusIcon} | ${cleanDetails} |`);
    }
  }
  lines.push("");

  // Target Sponsorship Directory Recommendations
  if (project.sponsorResearch && project.sponsorResearch.sponsors.length > 0) {
    lines.push("## 6. Sponsor Program Recommendations");
    lines.push("");
    lines.push(`> Source: Directory-based recommendations (${project.sponsorResearch.sponsors.length} programs matched). Not live verified.`);
    lines.push("");
    lines.push("| Sponsor | Sector | Tier | Indicative Contribution | Official Link | Last Checked |");
    lines.push("| :--- | :--- | :--- | :--- | :--- | :--- |");
    for (const sp of project.sponsorResearch.sponsors) {
      const link = sp.officialProgramLink || sp.sourceUrl;
      lines.push(`| **${sp.name}** | ${sp.sector} | \`${sp.tierLabel}\` | ${sp.typicalContribution} | [Link](${link}) | ${sp.lastChecked || "N/A"} |`);
    }
    lines.push("");
  }

  // Outreach Review Status
  if (project.outreachReview && project.outreachReview.drafts.length > 0) {
    lines.push("## 7. Sponsor Outreach Review Pipeline");
    lines.push("");
    lines.push(`Total drafts generated: ${project.outreachReview.drafts.length} · Safety Policy: Local draft mode only (no external dispatch).`);
    lines.push("");
    for (const d of project.outreachReview.drafts) {
      const isReviewed = project.reviewedDraftIds?.[d.id] ? "✅ Reviewed" : "⏳ Pending Review";
      lines.push(`### 📧 ${d.tier} (${isReviewed})`);
      lines.push(`- **Subject:** ${d.subject}`);
      lines.push(`- **Recipient Role:** ${d.recipientRole}`);
      lines.push(`- **Call To Action:** ${d.callToAction}`);
      lines.push("");
    }
  }

  // Creative Studio Assets
  if (project.creatives && project.creatives.length > 0) {
    lines.push("## 8. Template-based Creative Studio Brand Assets");
    lines.push("");
    for (const c of project.creatives) {
      lines.push(`### 🎨 ${c.title} (\`${c.dimension}\` · ${c.theme})`);
      lines.push(`- **Headline:** ${c.content.headline}`);
      lines.push(`- **Subheadline:** ${c.content.subheadline}`);
      lines.push(`- **Date & Venue:** ${c.content.eventDate} | ${c.content.venue}`);
      lines.push(`- **Badge:** ${c.content.badge}`);
      lines.push(`- **Created:** ${c.createdAt}`);
      lines.push("");
    }
  }

  // Safety & Provenance
  lines.push("## 9. Operational Provenance & Safety Policy");
  lines.push("");
  lines.push("- **Autonomous Execution Guarantee:** Every tool execution requires explicit organizer approval prior to execution.");
  lines.push("- **Deterministic Calculations:** All financial budgets and vector rendering computations are executed mathematically with zero hallucinations.");
  lines.push("- **Evidence Ledger:** Chronological append-only audit log stored in local browser workspace. Not cryptographically signed or tamper-proof.");
  lines.push("- **Outreach Safety Policy:** All sponsor communications and email pitches remain strictly in local draft mode. No emails or network requests are dispatched without organizer authorization.");
  lines.push("");
  lines.push("---");
  lines.push("*Report generated by OpsPilot — Unified AI Operations Workspace.*");

  return lines.join("\n");
}

/**
 * Triggers a browser file download for text/json content.
 */
export function downloadReportFile(filename: string, content: string, mimeType: string): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
